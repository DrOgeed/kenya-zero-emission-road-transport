# --------------------------------------------------------------------------
# Reading
# --------------------------------------------------------------------------
def read_datafile_via_glpsol(datafile: Path, declarations_model: Path,
                             params: list[str] | None = None,
                             param_index: dict[str, list[str]] | None = None) -> tuple[dict, dict]:
    """Parse a GMPL data file by letting glpsol evaluate it.

    ``declarations_model`` must declare every set/param present in the data
    file (e.g. the model file that shipped with the data). Only the
    declaration lines (``set``/``param`` up to the first ``var``) are used.
    Returns (sets, params) in tidy form (all entries, including defaults).
    """
    param_index = param_index or PARAM_INDEX
    text = Path(declarations_model).read_text(encoding="utf-8", errors="ignore")
    head = text.split("\nvar ")[0]
    data_text = Path(datafile).read_text(encoding="utf-8", errors="ignore")
    declared_sets = re.findall(r"^set\s+(\w+)\s*;", head, flags=re.M)
    present = set(re.findall(r"^param\s+(\w+)", data_text, flags=re.M))
    wanted = [p for p in (params or sorted(present)) if p in param_index]
    with tempfile.TemporaryDirectory() as tmp:
        tmp = Path(tmp)
        lines = [head, "\n"]
        for s in declared_sets:
            lines.append(f'printf {{x in {s}}} "S|{s}|%s\\n", x > "{tmp}/s_{s}.txt";\n')
        for p in wanted:
            idx = param_index[p]
            dummies = [f"i{k}" for k in range(len(idx))]
            dom = ", ".join(f"{d} in {s}" for d, s in zip(dummies, idx))
            fmt = "|".join(["%s"] * len(idx))
            args = ", ".join(dummies)
            lines.append(
                f'printf {{{dom}}} "{p}|{fmt}|%.10g\\n", {args}, {p}[{args}] > "{tmp}/p_{p}.txt";\n')
        lines.append("end;\n")
        mod = tmp / "dump.mod"
        mod.write_text("".join(lines))
        res = subprocess.run(["glpsol", "--check", "-m", str(mod), "-d", str(datafile)],
                             capture_output=True, text=True)
        if res.returncode != 0:
            raise RuntimeError(res.stdout[-3000:] + res.stderr[-2000:])
        sets: dict[str, list[str]] = {}
        for s in declared_sets:
            sf = tmp / f"s_{s}.txt"
            sets[s] = []
            if sf.exists():
                for line in sf.read_text().splitlines():
                    sets[s].append(line.split("|", 2)[2])
        out = {}
        for p in wanted:
            f = tmp / f"p_{p}.txt"
            cols = param_index[p] + ["VALUE"]
            if not f.exists() or f.stat().st_size == 0:
                out[p] = pd.DataFrame(columns=cols)
                continue
            df = pd.read_csv(f, sep="|", header=None, dtype=str)
            df = df.iloc[:, 1:]
            df.columns = cols
            df["VALUE"] = df["VALUE"].astype(float)
            out[p] = df
    return sets, out


# --------------------------------------------------------------------------
# Writing
# --------------------------------------------------------------------------
def _fmt(v: float) -> str:
    if float(v).is_integer():
        return str(int(v))
    return f"{v:.8g}"


def write_datafile(path: Path, sets: dict[str, list], params: dict[str, pd.DataFrame],
                   defaults: dict[str, float] | None = None, header: str = "") -> None:
    """Write a GMPL data file in tuple form, readable by MUIO's v5.7 model."""
    defaults = {**PARAM_DEFAULT, **(defaults or {})}
    out = [f"# {line}\n" for line in header.splitlines()]
    for s in SET_ORDER:
        vals = sets.get(s, [])
        out.append(f"set {s} := {' '.join(str(v) for v in vals)} ;\n")
    out.append("param TradeRoute default 0 := ;\n")
    for p in sorted(PARAM_INDEX):
        df = params.get(p)
        d = defaults.get(p, 0.0)
        out.append(f"param {p} default {_fmt(d)} :=\n")
        if df is not None and len(df):
            idx = PARAM_INDEX[p]
            sub = df[idx + ["VALUE"]]
            for row in sub.itertuples(index=False):
                *keys, val = row
                out.append(" ".join(str(k) for k in keys) + " " + _fmt(val) + "\n")
        out.append(";\n")
    out.append("end;\n")
    Path(path).write_text("".join(out), encoding="utf-8")
